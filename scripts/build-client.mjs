import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [source, styles, manifest] = await Promise.all([
  readFile(resolve(root, 'src/client.js'), 'utf8'),
  readFile(resolve(root, 'src/client.css'), 'utf8'),
  readFile(resolve(root, 'package.json'), 'utf8').then(JSON.parse),
]);
// This tiny source is intentionally plain JS: no JSX, dependencies, or second React.
if (/^\s*import\s/m.test(source)) throw new Error('Client source must resolve runtime modules through DSH.');
const body = source.replace(/^export (?=(?:function|const)\b)/gm, '');
if (/^export\s/m.test(body)) throw new Error('Unsupported client export: update the explicit build wrapper.');
const bundle = `// Generated by scripts/build-client.mjs. React is external and supplied by DSH.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory(require) {\n${body}\n    return createClientPlugin(require('react'), ${JSON.stringify(styles)}, require('react-dom'));\n  },\n});\n`;
await mkdir(resolve(root, 'dist'), { recursive: true });
await writeFile(resolve(root, 'dist/client.js'), bundle, 'utf8');
console.log(`Built dist/client.js (${Buffer.byteLength(bundle)} bytes; external: react, react-dom)`);
